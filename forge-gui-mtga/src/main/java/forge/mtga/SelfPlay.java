    /** A ranked player's view after a match: the rank change matches the outcome, and the client's answers and profile.json follow it. */
    private static boolean checkRank(String match, forge.mtga.social.RankService rank, forge.mtga.profile.FileProfileStore store, String outcome, String who) {
        com.google.gson.JsonObject change = rank.awaitMatch(match, 6_000);
        if (change == null) { System.out.println("  PROBLEM: " + who + " got no rank change"); return false; }
        com.google.gson.JsonObject progress = forge.mtga.social.RankService.progress(change), from = change.getAsJsonObject("old"), to = change.getAsJsonObject("new");
        String reason = change.get("reason").getAsString();
        System.out.println("  rank " + who + ": " + outcome + " (" + reason + ") " + progress);
        boolean ok = outcome.equals(change.get("result").getAsString()) && "Constructed".equals(progress.get("rankUpdateType").getAsString())
                && progress.get("seasonOrdinal").getAsInt() > 0;
        int oldPos = pos(from), newPos = pos(to);
        if ("applied".equals(reason)) {
            ok &= outcome.equals("win") ? newPos > oldPos : outcome.equals("loss") ? newPos <= oldPos : newPos == oldPos;
        } else {
            ok &= newPos == oldPos;
        }
        com.google.gson.JsonObject combined = rank.combinedRankInfo();
        ok &= combined.get("constructedClass").getAsString().equals(to.get("class").getAsString()) && combined.get("constructedStep").getAsInt() == to.get("step").getAsInt();
        forge.mtga.profile.Profile p = store.load();
        ok &= p.rank.rankClass.equals(to.get("class").getAsString()) && p.rank.tier == to.get("level").getAsInt();
        ok &= rank.seasonAndRankDetails().getAsJsonArray("constructedRankInfo").size() == 21;
        if (!ok) System.out.println("  PROBLEM: " + who + "'s rank change, combined rank " + combined + " or profile rank " + p.rank.rankClass + " " + p.rank.tier + " is wrong");
        return ok;
    }

    /**
     * A player's mastery after an online match: the verdict carries the XP (250 for playing, +150 for a win, inside the daily cap), the
     * progress follows it, and profile.json owns exactly the track's first 2 x `level` cosmetics (owned.all off).
     */
    private static boolean checkMastery(String match, forge.mtga.social.MasteryService mastery, forge.mtga.profile.FileProfileStore store, String outcome, String who) {
        int before = mastery.xp();
        com.google.gson.JsonObject v = mastery.awaitVerdict(match, 6_000);
        int paid = v != null && v.has("mastery") ? v.getAsJsonObject("mastery").get("xp").getAsInt() : -1;
        int expected = outcome.equals("win") ? 400 : 250;
        forge.mtga.profile.Profile p = store.load();
        List<String[]> track = mastery.track();
        Set<String> owned = new java.util.HashSet<>();
        owned.addAll(p.owned.avatars); owned.addAll(p.owned.sleeves); owned.addAll(p.owned.pets); owned.addAll(p.owned.emotes); owned.addAll(p.owned.titles);
        int grantedItems = Math.min(track.size(), 2 * mastery.level());     // two rewards per level
        boolean grantsOk = owned.size() == grantedItems;
        for (int i = 0; i < grantedItems; i++) grantsOk &= owned.contains(track.get(i)[1]);
        System.out.println("  mastery " + who + ": " + outcome + " +" + paid + " XP, total " + mastery.xp() + ", level " + mastery.level() + ", owned " + owned.size());
        boolean ok = paid == expected && mastery.xp() == before + paid && !p.owned.all && grantsOk && track.size() > 2000;
        if (!ok) System.out.println("  PROBLEM: " + who + "'s mastery: paid " + paid + " (expected " + expected + "), xp " + before + " -> " + mastery.xp() + ", owned.all " + p.owned.all + ", grants " + grantsOk);
        return ok;
    }

    /**
     * A player's quest counters of an online match (the host's engine counted both seats; the guest's came as frame METRICS) and their effect:
     * MatchPlayed, MatchWon as the outcome, some gameplay counted; posted to the coordinator, the quests whose counter is there move, the others not.
     */
    private static boolean checkQuests(String match, com.google.gson.JsonObject metrics, forge.mtga.social.QuestService quests, String outcome, String who) {
        System.out.println("  quests " + who + ": counters " + metrics);
        if (metrics == null) { System.out.println("  PROBLEM: " + who + " got no quest counters"); return false; }
        boolean ok = metrics.has("MatchPlayed") && metrics.has("MatchWon") == "win".equals(outcome)
                && (metrics.has("LandsPlayed") || metrics.has("SpellsCast"));
        com.google.gson.JsonArray before = quests.quests().deepCopy();
        metrics.addProperty("RankedPlayed", 1);
        com.google.gson.JsonArray moved = quests.progress(match, metrics);
        java.util.Map<String, String> metricOf = java.util.Map.ofEntries(java.util.Map.entry("PlayRanked", "RankedPlayed"), java.util.Map.entry("AttackCreatures", "CreaturesAttacked"),
                java.util.Map.entry("CastWhiteSpells", "WhiteSpellsCast"), java.util.Map.entry("CastBlueSpells", "BlueSpellsCast"), java.util.Map.entry("CastBlackSpells", "BlackSpellsCast"),
                java.util.Map.entry("CastRedSpells", "RedSpellsCast"), java.util.Map.entry("CastGreenSpells", "GreenSpellsCast"), java.util.Map.entry("CastInstantsSorceries", "InstantsAndSorceriesCast"),
                java.util.Map.entry("CastCreatures", "CreaturesCast"), java.util.Map.entry("PlayLands", "LandsPlayed"), java.util.Map.entry("DealDamage", "DamageDealt"),
                java.util.Map.entry("KillCreatures", "OpponentCreaturesDied"), java.util.Map.entry("CastArtifactsEnchantments", "ArtifactsAndEnchantmentsCast"));
        int expected = 0;
        for (com.google.gson.JsonElement e : before) {
            com.google.gson.JsonObject q = e.getAsJsonObject();
            String metric = metricOf.get(q.get("kind").getAsString());
            if (!q.get("done").getAsBoolean() && metric != null && metrics.has(metric)) expected++;
        }
        System.out.println("  quests " + who + ": " + moved.size() + " moved (expected " + expected + ") " + moved);
        ok &= moved.size() == expected;
        if (!ok) System.out.println("  PROBLEM: " + who + "'s quest counters or progress are wrong");
        return ok;
    }

